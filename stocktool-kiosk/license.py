def _hardware_id():
    try:
        import uuid
        mac = ':'.join(['{:02x}'.format((uuid.getnode() >> i) & 0xff)
                        for i in range(0,48,8)][::-1])
        return f"{socket.gethostname()}-{mac}"
    except: return socket.gethostname()

def _save_cache(data):
    try:
        os.makedirs(os.path.dirname(CACHE_FILE), exist_ok=True)
        json.dump({**data, "_cached_at": datetime.utcnow().isoformat()}, open(CACHE_FILE,"w"))
    except: pass

def _load_cache():
    try:
        data = json.load(open(CACHE_FILE))
        if datetime.utcnow() - datetime.fromisoformat(data["_cached_at"]) < timedelta(seconds=GRACE_PERIOD):
            return data
    except: pass
    return None

def validate_license(key=None):
    global _state
    key = key or _read_key()
    if not key:
        with _lock: _state.update({"valid":False,"checked":True,"error":"No licence key found in license.txt"})
        return False
    payload = {"license_key": key, "hardware_id": _hardware_id(), "domain": socket.gethostname()}
    try:
        data = requests.post(f"{LICENSE_SERVER}/api/validate", json=payload, timeout=VALIDATE_TIMEOUT).json()
        if data.get("valid"):
            act_id = None
            try:
                ar = requests.post(f"{LICENSE_SERVER}/api/activate",
                                   json={**payload,"hostname":socket.gethostname()}, timeout=VALIDATE_TIMEOUT).json()
                act_id = ar.get("activation_id")
            except: pass
            with _lock:
                _state.update({"valid":True,"checked":True,"license_key":key,
                               "activation_id":act_id,"customer":data.get("customer"),
                               "tier":data.get("tier_name"),"features":data.get("features",[]),
                               "expires_at":data.get("expires_at"),"days_left":data.get("days_until_expiry"),
                               "error":None,"last_ok":datetime.utcnow(),"server_down":False})
            _save_cache(data)
            print(f"[STOCKTOOL] \u2713 Valid \u2014 {data.get('customer','?')} \u00b7 {data.get('tier_name','')} \u00b7 features: {data.get('features',[])}")
            return True
        err = data.get("error","Licence invalid")
        with _lock: _state.update({"valid":False,"checked":True,"error":err})
        print(f"[STOCKTOOL] \u2717 {err}")
        return False
    except requests.exceptions.ConnectionError:
        return _grace("Cannot reach licence server")
    except requests.exceptions.Timeout:
        return _grace("Licence server timed out")
    except Exception as e:
        return _grace(str(e))

def _grace(reason):
    cache = _load_cache()
    if cache and cache.get("valid"):
        h = round((timedelta(seconds=GRACE_PERIOD)-(datetime.utcnow()-datetime.fromisoformat(cache["_cached_at"]))).total_seconds()/3600,1)
        with _lock:
            _state.update({"valid":True,"checked":True,
                           "features":cache.get("features",[]),
                           "error":f"\u26a0 Server offline \u2014 grace period ({h}h left)","server_down":True})
        return True
    with _lock: _state.update({"valid":False,"checked":True,"error":f"Server unreachable: {reason}","server_down":True})
    return False

def send_heartbeat():
    with _lock: key, act_id = _state.get("license_key"), _state.get("activation_id")
    if not key: return
    try:
        data = requests.post(f"{LICENSE_SERVER}/api/heartbeat",
                             json={"license_key":key,"activation_id":act_id}, timeout=VALIDATE_TIMEOUT).json()
        if data.get("valid"):
            with _lock: _state["last_ok"] = datetime.utcnow(); _state["server_down"] = False
    except: pass

def _heartbeat_loop():
    time.sleep(HEARTBEAT_EVERY)
    while True:
        try: send_heartbeat()
        except: pass
        time.sleep(HEARTBEAT_EVERY)

