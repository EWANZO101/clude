def init_license(app=None):
    """Call this on startup. Pass your Flask app to block if invalid.

    validate_license() makes up to two chained network calls (/api/validate,
    then /api/activate), each with an 8s timeout -- up to ~16s. This used to
    run inline here, inside create_app(), which runs *before*
    server_supervisor.py ever calls serve() to bind the port. On a slow or
    unreachable license server that delay alone could push total startup
    past main.py's 15s _wait_for_server() budget, so the embedded server
    would still be stuck validating a license when main.py gave up waiting
    and printed a (misleading) "port already in use" error -- the port was
    never the problem, the license check just hadn't finished yet.

    Fixed by running the initial check in a background thread instead, same
    as the heartbeat loop below it. The before_request gate already re-reads
    is_valid() on every request rather than freezing a decision made once at
    startup, so there's no correctness reason validate_license() needs to
    finish before the app starts serving -- it's briefly unlicensed (which
    the gate already handles) until the background check completes, instead
    of the whole server being unreachable for that same window."""
    t = threading.Thread(target=validate_license, daemon=True, name="LicenceValidate_STOCKTOOL")
    t.start()
    hb = threading.Thread(target=_heartbeat_loop, daemon=True, name="LicenceHeartbeat_STOCKTOOL")
    hb.start()
    if app:
        @app.before_request
        def _block():
            from flask import request, render_template
            if request.path.startswith(_EXEMPT_PREFIXES):
                return None
            if is_valid():
                return None
            return render_template("license_invalid.html", error=get_state().get("error")), 403
    return None
